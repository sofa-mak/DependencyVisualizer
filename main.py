# Импортируем модуль argparse (он встроен в Python) для работы с параметрами командной строки
import argparse

# Импортируем модуль sys для возможности выхода из программы с ошибкой
import sys

# Создаем функцию, которая будет собирать и проверять наши параметры
def get_arguments():
    # Создаем объект парсера. description - это описание программы, которое покажется при вызове справки
    parser = argparse.ArgumentParser(description="Инструмент визуализации графа зависимостей")

    # Добавляем параметр: Имя анализируемого пакета (строка, обязательный)
    # type=str означает, что аргумент должен быть текстом
    parser.add_argument("-p", "--package", type=str, required=True, help="Имя анализируемого пакета")
    
    # Добавляем параметр: URL-адрес репозитория или путь к файлу (строка, обязательный)
    parser.add_argument("-u", "--url", type=str, required=True, help="URL репозитория или путь к файлу")
    
    # Добавляем параметр: Режим работы с тестовым репозиторием (флаг, то есть либо есть, либо нет)
    # action="store_true" означает, что если флаг указан, значение будет True, иначе False
    parser.add_argument("-t", "--test-mode", action="store_true", help="Режим тестового репозитория")
    
    # Добавляем параметр: Имя сгенерированного файла (строка, по умолчанию graph.png)
    parser.add_argument("-o", "--output", type=str, default="graph.png", help="Имя файла с изображением графа")
    
    # Добавляем параметр: Режим вывода в ASCII-дерево (флаг)
    parser.add_argument("-a", "--ascii", action="store_true", help="Вывод зависимостей в виде ASCII-дерева")
    
    # Добавляем параметр: Максимальная глубина (целое число, по умолчанию 3)
    parser.add_argument("-d", "--depth", type=int, default=3, help="Максимальная глубина анализа")
    
    # Добавляем параметр: Подстрока для фильтрации (строка, по умолчанию пустая)
    parser.add_argument("-f", "--filter", type=str, default="", help="Подстрока для фильтрации пакетов")

    # Метод parse_args() считывает то, что ввел пользователь, и проверяет типы
    args = parser.parse_args()
    
    # ВОЗВРАЩАЕМ полученные и проверенные аргументы
    return args

# Главная функция, с которой начинается выполнение программы
def main():
    # Получаем аргументы, вызывая нашу функцию
    args = get_arguments()

    # Обработка ошибок (Этап 1, требование 4)
    # Проверяем, что глубина больше нуля. Если меньше или равно 0 - выдаем ошибку
    if args.depth <= 0:
        print("Ошибка: Глубина анализа должна быть больше 0.") # Выводим текст ошибки
        sys.exit(1) # Завершаем программу с кодом ошибки 1

    # Проверяем, что URL не пустой (хотя required=True уже это делает, но для надежности)
    if not args.url.strip():
        print("Ошибка: URL или путь к файлу не может быть пустым.")
        sys.exit(1)

    # Требование 3: Вывести все параметры в формате ключ-значение
    print("--- НАСТРОЙКИ ПРОГРАММЫ ---")
    print(f"Пакет: {args.package}") # Выводим имя пакета
    print(f"URL/Путь: {args.url}") # Выводим URL
    print(f"Режим тестового репозитория: {args.test_mode}") # Выводим True или False
    print(f"Файл изображения: {args.output}") # Выводим имя файла
    print(f"Режим ASCII: {args.ascii}") # Выводим True или False
    print(f"Максимальная глубина: {args.depth}") # Выводим глубину
    print(f"Подстрока фильтрации: '{args.filter}'") # Выводим фильтр
    print("---------------------------")

# Проверка: если этот файл запущен напрямую (а не импортирован), то вызываем main()
if __name__ == "__main__":
    main()